#!/usr/bin/env python3
"""Generate shared font-independent touch geometry for C++ and Android Canvas."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    icons = json.loads((ROOT / "config/touch-icons.json").read_text(encoding="utf-8"))
    cpp = ["// Generated by tools/generate-touch-icons.py; edit config/touch-icons.json.",
           "#pragma once", "#include <span>", "#include <string_view>",
           "namespace pinyon_shift::ui {", "struct TouchLine { float x0, y0, x1, y1; };",
           "struct TouchIcon { std::string_view name; float width, height; bool rectangular; std::span<const TouchLine> lines; };"]
    java = ["// Generated by tools/generate-touch-icons.py; edit config/touch-icons.json.",
            "package studio.deimos.pinyonshift;", "final class TouchIcons {",
            "    static final String[] NAMES = " + json.dumps(list(icons)).replace("[", "{").replace("]", "}") + ";",
            "    static final String[] TITLES = " + json.dumps([i["title"] for i in icons.values()]).replace("[", "{").replace("]", "}") + ";",
            "    static final float[][] BOUNDS = {",
            *["        {" + ",".join(f"{v:.6f}f" for v in i["bounds"]) + "}," for i in icons.values()],
            "    };", "    static final boolean[] RECT = {" + ",".join(str(i.get("rect", False)).lower() for i in icons.values()) + "};",
            "    static final float[][] LINES = {"]
    for name, icon in icons.items():
        segments = [(*a, *b) for path in icon["paths"] for a, b in zip(path, path[1:])]
        cpp += [f"inline constexpr TouchLine kTouchLines{name}[] = {{",
                *["    {" + ",".join(f"{v:.6f}f" for v in line) + "}," for line in segments], "};"]
        java += ["        {" + ",".join(f"{v:.6f}f" for line in segments for v in line) + "},"]
    cpp += ["inline constexpr TouchIcon kTouchIcons[] = {",
            *[f'    {{"{n}",{i["bounds"][0]:.6f}f,{i["bounds"][1]:.6f}f,{str(i.get("rect", False)).lower()},kTouchLines{n}}},' for n, i in icons.items()],
            "};", "inline const TouchIcon* FindTouchIcon(std::string_view name) {",
            "    for (const auto& icon : kTouchIcons) if (icon.name == name) return &icon;",
            "    return nullptr;", "}", "}  // namespace pinyon_shift::ui", ""]
    java += ["    };", "    private TouchIcons() {}", "}", ""]
    return {ROOT / "src/ui/touch_icons.h": "\n".join(cpp),
            ROOT / "android/java/studio/deimos/pinyonshift/TouchIcons.java": "\n".join(java)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, text in generate().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        parser.exit(1, "Regenerate touch icons: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
