#!/usr/bin/env python3
"""Generate shared font-independent touch geometry for C++ and Android Canvas."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Small controller hints remain vector paths, including in game menus without fonts.
HINT_GLYPHS = {
    "A": [[[0, 1], [.4, 0], [.8, 1]], [[.16, .6], [.64, .6]]],
    "B": [[[0, 0], [0, 1], [.55, 1], [.8, .8], [.8, .65], [.55, .5], [0, .5]],
          [[.55, .5], [.8, .3], [.8, .15], [.55, 0], [0, 0]]],
    "C": [[[.8, .1], [.6, 0], [.2, 0], [0, .2], [0, .8], [.2, 1], [.6, 1], [.8, .9]]],
    "K": [[[0, 0], [0, 1]], [[.8, 0], [0, .5], [.8, 1]]],
    "L": [[[0, 0], [0, 1], [.8, 1]]],
    "R": [[[0, 1], [0, 0], [.55, 0], [.8, .2], [.8, .35], [.55, .5], [0, .5]],
          [[.4, .5], [.8, 1]]],
    "S": [[[.8, .1], [.6, 0], [.2, 0], [0, .2], [.2, .5], [.6, .5], [.8, .8], [.6, 1], [0, 1]]],
    "T": [[[0, 0], [.8, 0]], [[.4, 0], [.4, 1]]],
    "X": [[[0, 0], [.8, 1]], [[.8, 0], [0, 1]]],
    "Y": [[[0, 0], [.4, .5], [.8, 0]], [[.4, .5], [.4, 1]]],
    "3": [[[0, 0], [.6, 0], [.8, .2], [.6, .5], [.2, .5]],
          [[.6, .5], [.8, .8], [.6, 1], [0, 1]]],
}


def hint_segments(icon):
    text = icon.get("hint", "")
    if not text:
        return []
    height = .20 if len(text) > 3 else .24
    width = (len(text) - 1) * height * 1.2 + height * .8
    x, y = -width / 2, icon["bounds"][1] - (.42 if len(text) > 3 else .36)
    return [((x + (index * 1.2 + a[0]) * height), y + a[1] * height,
             (x + (index * 1.2 + b[0]) * height), y + b[1] * height)
            for index, char in enumerate(text) for path in HINT_GLYPHS[char]
            for a, b in zip(path, path[1:])]


def classic_segments(icon):
    text = icon.get("hint", "")
    if not text:
        return [(*a, *b) for path in icon["paths"] for a, b in zip(path, path[1:])]
    units = (len(text) - 1) * 1.2 + .8
    size = min(.7, 1.4 * icon["bounds"][0] / units)
    x, y = -units * size / 2, -size / 2
    return [(x + (index * 1.2 + a[0]) * size, y + a[1] * size,
             x + (index * 1.2 + b[0]) * size, y + b[1] * size)
            for index, char in enumerate(text) for path in HINT_GLYPHS[char]
            for a, b in zip(path, path[1:])]


def generate():
    icons = json.loads((ROOT / "config/touch-icons.json").read_text(encoding="utf-8"))
    cpp = ["// Generated by tools/generate-touch-icons.py; edit config/touch-icons.json.",
           "#pragma once", "#include <span>", "#include <string_view>",
           "namespace pinyon_shift::ui {", "struct TouchLine { float x0, y0, x1, y1; };",
           "struct TouchIcon { std::string_view name; float width, height; bool rectangular; std::span<const TouchLine> lines, hints, classic; };"]
    java = ["// Generated by tools/generate-touch-icons.py; edit config/touch-icons.json.",
            "package studio.deimos.pinyonshift;", "final class TouchIcons {",
            "    static final String[] NAMES = " + json.dumps(list(icons)).replace("[", "{").replace("]", "}") + ";",
            "    static final String[] TITLES = " + json.dumps([i["title"] for i in icons.values()]).replace("[", "{").replace("]", "}") + ";",
            "    static final float[][] BOUNDS = {",
            *["        {" + ",".join(f"{v:.6f}f" for v in i["bounds"]) + "}," for i in icons.values()],
            "    };", "    static final boolean[] RECT = {" + ",".join(str(i.get("rect", False)).lower() for i in icons.values()) + "};",
            "    static final float[][] LINES = {"]
    for name, icon in icons.items():
        segments = [(*a, *b) for path in icon["paths"] for a, b in zip(path, path[1:])]
        cpp += [f"inline constexpr TouchLine kTouchLines{name}[] = {{",
                *["    {" + ",".join(f"{v:.6f}f" for v in line) + "}," for line in segments], "};"]
        hints = hint_segments(icon)
        if hints:
            cpp += [f"inline constexpr TouchLine kTouchHints{name}[] = {{",
                    *["    {" + ",".join(f"{v:.6f}f" for v in line) + "}," for line in hints], "};"]
        cpp += [f"inline constexpr TouchLine kTouchClassic{name}[] = {{",
                *["    {" + ",".join(f"{v:.6f}f" for v in line) + "}," for line in classic_segments(icon)], "};"]
        java += ["        {" + ",".join(f"{v:.6f}f" for line in segments for v in line) + "},"]
    cpp += ["inline constexpr TouchIcon kTouchIcons[] = {",
            *[f'    {{"{n}",{i["bounds"][0]:.6f}f,{i["bounds"][1]:.6f}f,{str(i.get("rect", False)).lower()},kTouchLines{n},'
              + (f'kTouchHints{n}' if i.get("hint") else '{}') + f',kTouchClassic{n}' + '},' for n, i in icons.items()],
            "};", "inline const TouchIcon* FindTouchIcon(std::string_view name) {",
            "    for (const auto& icon : kTouchIcons) if (icon.name == name) return &icon;",
            "    return nullptr;", "}", "}  // namespace pinyon_shift::ui", ""]
    java += ["    };", "    static final float[][] HINTS = {",
             *["        {" + ",".join(f"{v:.6f}f" for line in hint_segments(i) for v in line) + "},"
               for i in icons.values()],
             "    };", "    static final float[][] CLASSIC = {",
             *["        {" + ",".join(f"{v:.6f}f" for line in classic_segments(i) for v in line) + "},"
               for i in icons.values()],
             "    };", "    private TouchIcons() {}", "}", ""]
    return {ROOT / "src/ui/touch_icons.h": "\n".join(cpp),
            ROOT / "android/java/studio/deimos/pinyonshift/TouchIcons.java": "\n".join(java)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, text in generate().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        parser.exit(1, "Regenerate touch icons: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
