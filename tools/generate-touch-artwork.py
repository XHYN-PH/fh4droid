#!/usr/bin/env python3
"""Build the shared control atlas from square SVG icons. --check is stdlib-only.

Regeneration uses Pillow 11.3.0 and CairoSVG 2.8.2. SVG aspect ratios are kept
unchanged. Native gameplay and the Android editor consume identical PNG bytes.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import struct
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
TILE, COLS, ROWS = 160, 4, 5
PNG = ROOT / 'android/art/touch-controls.png'
HEADER = ROOT / 'src/ui/touch_artwork.h'
JAVA = ROOT / 'android/java/studio/deimos/pinyonshift/TouchArtwork.java'
SPEC = ROOT / 'config/touch-artwork.json'
VECTORS = ROOT / 'config/touch-artwork'


def sources():
    spec = json.loads(SPEC.read_text(encoding='utf-8'))
    legacy = json.loads((ROOT / 'config/touch-icons.json').read_text(encoding='utf-8'))
    if list(spec) != list(legacy):
        raise ValueError('Artwork order does not match input controls')
    if (VECTORS / 'LICENSE.txt').read_text(encoding='utf-8') != (
            ROOT / 'android/res/raw/control_artwork_license.txt').read_text(encoding='utf-8'):
        raise ValueError('The packaged icon license must match the source license')
    for item in spec.values():
        name = item['svg']
        if not re.fullmatch(r'[a-z0-9-]+\.svg', name):
            raise ValueError('Invalid SVG filename')
        data = (VECTORS / name).read_bytes()
        if b'<!' in data or len(data) > 16384:
            raise ValueError('Only small self-contained SVG icons are allowed')
        svg = ET.fromstring(data)
        if svg.get('viewBox') != '0 0 24 24' or svg.get('width') != svg.get('height'):
            raise ValueError('Icons must use a square 24-unit design grid')
        allowed = {'svg', 'g', 'path', 'circle', 'rect', 'line', 'polyline', 'polygon',
                   'defs', 'linearGradient', 'stop'}
        local_ids = {node.get('id') for node in svg.iter() if node.get('id')}
        for node in svg.iter():
            if node.tag.rsplit('}', 1)[-1] not in allowed or any('href' in a for a in node.attrib):
                raise ValueError('SVG must contain only local icon geometry')
            for value in node.attrib.values():
                if 'url(' in value:
                    match = re.fullmatch(r'url\(#([A-Za-z0-9_-]+)\)', value)
                    if not match or match.group(1) not in local_ids:
                        raise ValueError('SVG paint references must resolve inside the icon')
    return spec, legacy


def source_hash():
    spec, _ = sources()
    digest = hashlib.sha256()
    for path in [SPEC, ROOT / 'config/touch-icons.json', Path(__file__).resolve(),
                 *sorted({VECTORS / item['svg'] for item in spec.values()})]:
        digest.update(path.read_text(encoding='utf-8').encode('utf-8'))
    return digest.hexdigest()


def outputs(data):
    spec, _ = sources()
    digest = hashlib.sha256(data).hexdigest()
    header = ['// Generated by tools/generate-touch-artwork.py.',
              '// source-sha256: ' + source_hash(), '// png-sha256: ' + digest,
              '#pragma once', '#include <cstdint>', 'namespace pinyon_shift::ui {',
              f'inline constexpr unsigned kTouchArtworkTile={TILE}, kTouchArtworkColumns={COLS}, kTouchArtworkRows={ROWS};',
              'inline constexpr uint8_t kTouchArtworkPng[] = {']
    header += ['  ' + ','.join(str(b) for b in data[i:i+24]) + ',' for i in range(0, len(data), 24)]
    header += ['};', '} // namespace pinyon_shift::ui', '']
    java = '''// Generated by tools/generate-touch-artwork.py.
// source-sha256: SOURCE_HASH
// png-sha256: PNG_HASH
package studio.deimos.pinyonshift;
import android.content.Context;
import android.graphics.*;
import java.io.*;
final class TouchArtwork {
  static final int TILE=160,COLUMNS=4,ROWS=5;
  static final String[] CAPTIONS=CAPTION_ARRAY;
  private static Bitmap atlas;
  static synchronized Bitmap bitmap(Context context){
    if(atlas==null)try(InputStream in=context.getAssets().open("touch-controls.png")){
      BitmapFactory.Options options=new BitmapFactory.Options();options.inScaled=false;
      atlas=BitmapFactory.decodeStream(in,null,options);
      if(atlas!=null&&(atlas.getWidth()!=TILE*COLUMNS||atlas.getHeight()!=TILE*ROWS*3)){atlas.recycle();atlas=null;}
    }catch(IOException error){android.util.Log.w("FH4Droid","Control artwork unavailable",error);}
    return atlas;
  }
  static Rect source(int icon,int plane){int x=icon%COLUMNS*TILE,y=(icon/COLUMNS+plane*ROWS)*TILE;return new Rect(x,y,x+TILE,y+TILE);}
  private TouchArtwork(){}
}
'''.replace('SOURCE_HASH', source_hash()).replace('PNG_HASH', digest).replace(
        'CAPTION_ARRAY', '{' + ','.join(json.dumps(v['caption']) for v in spec.values()) + '}')
    return {HEADER: '\n'.join(header), JAVA: java}


def render():
    from PIL import Image, ImageDraw, ImageFont
    import cairosvg
    spec, legacy = sources()
    scale, size = 4, TILE * 4
    radius = size / 2
    atlas = Image.new('RGBA', (TILE * COLS, TILE * ROWS * 3))
    for i, (key, item) in enumerate(spec.items()):
        for plane in range(3):
            cell = Image.new('RGBA', (size, size))
            draw = ImageDraw.Draw(cell)
            if plane == 0:
                svg = ET.fromstring((VECTORS / item['svg']).read_bytes())
                svg.set('color', '#ffffff')
                svg.set('stroke', '#ffffff')
                svg.set('stroke-width', str(item.get('stroke', 1.25)))
                if item.get('filled'):
                    svg.set('fill', '#ffffff')
                extent = round(radius * item.get('glyph_scale', 1.3))
                # Render once to a SQUARE; never force a symbol into its button's
                # rectangular bounds. In particular, camera lenses stay round.
                raw = cairosvg.svg2png(bytestring=ET.tostring(svg), output_width=extent,
                                      output_height=extent)
                symbol = Image.open(io.BytesIO(raw)).convert('RGBA')
                offset = item.get('offset', [0, -.02])
                cell.alpha_composite(symbol, (round(radius * (1 + offset[0]) - extent/2),
                                              round(radius * (1 + offset[1]) - extent/2)))
            elif plane == 1:
                button = item.get('button', '')
                if button:
                    # A readable code badge replaces the squeezed combined name.
                    f = ImageFont.load_default(size=round(radius * (.23 if len(button)>2 else .28)))
                    bounds = draw.textbbox((0, 0), button, font=f)
                    half = min(radius * .60, (bounds[2]-bounds[0])/2 + radius*.10)
                    cy = radius * (1 + item.get('badge_y', -.70))
                    draw.rounded_rectangle((radius-half, cy-radius*.14, radius+half, cy+radius*.14),
                                           radius=radius*.09, fill=(255,255,255,24),
                                           outline=(255,255,255,100), width=max(1, round(radius*.012)))
                    draw.text((radius, cy), button, font=f, anchor='mm', fill='white',
                              stroke_width=max(0, round(radius*.003)))
                label = item['label']
                n = round(radius * .23)
                max_width = radius * min(1.08, legacy[key]['bounds'][0]*1.70)
                f = ImageFont.load_default(size=n)
                while draw.textbbox((0,0),label,font=f)[2] > max_width and n > 8:
                    n -= 1
                    f = ImageFont.load_default(size=n)
                y = radius * (1 + min(.73, legacy[key]['bounds'][1]-.20))
                draw.text((radius,y), label, font=f, anchor='mm', fill='white',
                          stroke_width=max(0,round(radius*.002)))
            else:
                caption = legacy[key].get('hint')
                if not caption:
                    box = ((i%COLS)*TILE, (i//COLS)*TILE, (i%COLS+1)*TILE, (i//COLS+1)*TILE)
                    atlas.paste(atlas.crop(box), ((i%COLS)*TILE, (i//COLS+plane*ROWS)*TILE))
                    continue
                n = round(size*.38)
                f = ImageFont.load_default(size=n)
                while draw.textbbox((0,0),caption,font=f)[2] > size*min(.88,legacy[key]['bounds'][0]*.91):
                    n -= 1
                    f = ImageFont.load_default(size=n)
                draw.text((radius,size*.44), caption, font=f, anchor='mm', fill='white')
            cell = cell.resize((TILE,TILE), Image.Resampling.LANCZOS)
            atlas.paste(cell, ((i%COLS)*TILE,(i//COLS+plane*ROWS)*TILE))
    result = io.BytesIO()
    atlas.save(result, format='PNG', optimize=True)
    return result.getvalue()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sources()
    data = PNG.read_bytes() if args.check else render()
    if data[:8] != b'\x89PNG\r\n\x1a\n' or struct.unpack('>II',data[16:24]) != (TILE*COLS,TILE*ROWS*3):
        raise SystemExit('Invalid control atlas')
    expected = outputs(data)
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p,text in expected.items()
                 if not p.exists() or p.read_text(encoding='utf-8') != text]
        if stale:
            raise SystemExit('Stale artwork files: '+', '.join(stale))
    else:
        PNG.write_bytes(data)
        for path,text in expected.items():
            path.write_text(text, encoding='utf-8')
    print(f'Shared SVG control artwork: 20 icons, code badges and action labels; {len(data)} PNG bytes')


if __name__ == '__main__':
    main()
